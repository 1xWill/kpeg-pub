function splitChecklistDetail(detail: string): [string, string] | null {
  const separatorIndex = detail.indexOf("->");
  if (separatorIndex < 0) {
    return null;
  }
  return [
    detail.slice(0, separatorIndex).trimEnd(),
    detail.slice(separatorIndex + 2).trimStart(),
  ];
}

